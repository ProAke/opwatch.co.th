function makeRunSteps(runId: string, flow: Flow, failedIdxs: number[]): RunStep[] {
  return flow.steps.map((s, i) => {
    const failed = failedIdxs.includes(i);
    const skipped = failedIdxs.length > 0 && i > Math.max(...failedIdxs) && failedIdxs[0] < i - 2;
    const status = failed ? "failed" : skipped ? "skipped" : "passed";
    const [ok, bad] = stepDetail[s.kind] ?? ["ผ่าน", "ไม่ผ่าน"];
    return {
      id: `${runId}_st${i}`,
      runId,
      idx: i + 1,
      kind: s.kind,
      name: s.name,
      status: status as RunStep["status"],
      startedAt: null,
      durationMs: status === "skipped" ? 0 : 420 + ((i * 613) % 2600),
      detail: status === "failed" ? bad : status === "skipped" ? "ข้ามเพราะขั้นก่อนหน้าล้มเหลว" : ok,
      evidence:
        status === "passed" || status === "failed"
          ? `NNN-${String(i + 1).padStart(2, "0")}-${s.kind}.png`
          : null,
      aiNote: s.kind === "ai.review" ? (status === "failed" ? "พบความเสี่ยง: ยอดภาษีหายไป 700 บาท" : "ไม่พบความเสี่ยง") : undefined,
    };
  });
}

